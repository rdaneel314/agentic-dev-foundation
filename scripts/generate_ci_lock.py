"""Lock a validated tools environment using official PyPI wheel hashes; never installs."""
from concurrent.futures import ThreadPoolExecutor
from importlib import metadata
import json
from pathlib import Path
import sys
from urllib.request import urlopen

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]


def dependency_closure():
    roots = [Requirement(line) for line in (ROOT / "requirements-ci.txt").read_text().splitlines()
             if line.strip() and not line.startswith("#")]
    queue = [(r, "") for r in roots]
    selected, visited = {}, set()
    while queue:
        req, extra = queue.pop()
        name = canonicalize_name(req.name)
        dist = metadata.distribution(req.name)
        if not req.specifier.contains(dist.version, prereleases=True):
            raise ValueError(f"Installed version violates constraint: {name}")
        selected[name] = dist
        for context in {"", *req.extras}:
            key = (name, context)
            if key in visited:
                continue
            visited.add(key)
            for raw in dist.requires or []:
                child = Requirement(raw)
                applies = False
                for platform, os_name, system in [("win32", "nt", "Windows"), ("linux", "posix", "Linux"), ("darwin", "posix", "Darwin")]:
                    environment = dict(default_environment(), python_version="3.13", python_full_version="3.13.5",
                                       sys_platform=platform, os_name=os_name, platform_system=system, extra=context)
                    applies |= child.marker is None or child.marker.evaluate(environment)
                if applies:
                    queue.append((child, context))
    return selected


def release(item):
    name, dist = item
    url = f"https://pypi.org/pypi/{name}/{dist.version}/json"
    with urlopen(url, timeout=30) as response:
        data = json.load(response)
    wheels = [f for f in data["urls"] if f["packagetype"] == "bdist_wheel" and not f.get("yanked")]
    if not wheels or data["info"]["version"] != dist.version:
        raise ValueError(f"No reviewed wheel release: {name}")
    return name, {"version": dist.version, "source": url,
                  "requires_python": data["info"].get("requires_python"),
                  "requires_dist": data["info"].get("requires_dist") or [],
                  "wheels": [{"filename": f["filename"], "sha256": f["digests"]["sha256"]} for f in wheels]}


def main():
    selected = dependency_closure()
    with ThreadPoolExecutor(max_workers=6) as pool:
        releases = dict(pool.map(release, sorted(selected.items())))
    lines = ["# Python 3.13 tools, pinned from a validated existing environment.",
             "# Generated by scripts/generate_ci_lock.py; PyPI non-yanked wheel SHA-256 hashes.",
             "# Install with --only-binary=:all: --require-hashes. No source builds."]
    for name, info in sorted(releases.items()):
        lines.append(f"{name}=={info['version']} \\")
        hashes = sorted({f["sha256"] for f in info["wheels"]})
        lines.extend("    --hash=sha256:" + h + (" \\" if i < len(hashes) - 1 else "") for i, h in enumerate(hashes))
    (ROOT / "requirements-ci.lock").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (ROOT / "docs/dependency-provenance.json").write_text(json.dumps(releases, indent=2) + "\n", encoding="utf-8")
    print(f"Locked {len(releases)} packages using official wheel hashes; no installation performed.")


if __name__ == "__main__":
    main()
